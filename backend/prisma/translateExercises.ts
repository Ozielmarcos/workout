// ---------------------------------------------------------------------------
// MyMemory API: fallback gratuito (sem chave de API)
// ---------------------------------------------------------------------------
type MyMemoryResponse = {
  responseStatus: number;
  responseData: { translatedText: string };
};

async function translateWithMyMemory(text: string): Promise<string> {
  try {
    const url = `https://api.mymemory.translated.net/get?q=${encodeURIComponent(text)}&langpair=en|pt-BR`;
    const res = await fetch(url);
    if (!res.ok) return text;
    const data = (await res.json()) as MyMemoryResponse;
    if (data.responseStatus === 200) return data.responseData.translatedText;
  } catch {
    // sem tradução disponível
  }
  return text;
}

function sleep(ms: number) {
  return new Promise<void>((r) => setTimeout(r, ms));
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main() {
  const exercises = await prisma.exercise.findMany({
    select: { id: true, name: true },
    orderBy: { name: 'asc' },
  });

  let staticHits = 0;
  let apiCalls = 0;
  let fallbacks = 0;

  console.log(`Traduzindo ${exercises.length} exercícios...\n`);

  for (const ex of exercises) {
    const staticPt = STATIC_MAP[ex.name];
    let namePt: string;

    if (staticPt) {
      namePt = staticPt;
      staticHits++;
    } else {
      namePt = await translateWithMyMemory(ex.name);
      apiCalls++;
      if (namePt === ex.name) fallbacks++;
      // Respeitar rate limit: pausa de 300ms a cada chamada
      await sleep(300);
      if (apiCalls % 20 === 0) await sleep(2000);
    }

    await prisma.exercise.update({ where: { id: ex.id }, data: { namePt } });
    console.log(`[${staticPt ? 'MAP' : 'API'}] ${ex.name} → ${namePt}`);
  }

  console.log(`\nConcluído!`);
  console.log(`  Mapa estático : ${staticHits}`);
  console.log(`  API           : ${apiCalls} (${fallbacks} sem tradução)`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
